create table content_special_request (
    id bigint generated by default as identity primary key,
    property_id bigint not null,
    request_code varchar(120) not null,
    enabled boolean not null,
    constraint fk_special_request_property foreign key (property_id) references property(id)
);

create table content_amenity (
    id bigint generated by default as identity primary key,
    property_id bigint not null,
    amenity_code varchar(120) not null,
    enabled boolean not null,
    constraint fk_amenity_property foreign key (property_id) references property(id)
);

create table room_type (
    id bigint generated by default as identity primary key,
    property_id bigint not null,
    name varchar(120) not null,
    is_master boolean not null,
    master_room_name varchar(120),
    occupancy integer not null,
    constraint fk_room_type_property foreign key (property_id) references property(id)
);

create table floor_configuration (
    id bigint generated by default as identity primary key,
    property_id bigint not null,
    floor_name varchar(120) not null,
    room_type_name varchar(120) not null,
    room_count integer not null,
    start_number integer not null,
    constraint fk_floor_config_property foreign key (property_id) references property(id)
);

create table inventory_room (
    id bigint generated by default as identity primary key,
    property_id bigint not null,
    floor_name varchar(120) not null,
    room_type_name varchar(120) not null,
    room_number varchar(30) not null,
    constraint uk_inventory_room_number unique(property_id, room_number),
    constraint fk_inventory_room_property foreign key (property_id) references property(id)
);

create table chart_of_account (
    id bigint generated by default as identity primary key,
    property_id bigint not null,
    ledger_code varchar(80) not null,
    ledger_name varchar(150) not null,
    category varchar(80) not null,
    constraint fk_chart_of_account_property foreign key (property_id) references property(id)
);

create table revenue_mapping (
    id bigint generated by default as identity primary key,
    property_id bigint not null,
    pms_item varchar(120) not null,
    ledger_code varchar(80) not null,
    constraint fk_revenue_mapping_property foreign key (property_id) references property(id)
);

create table payment_method (
    id bigint generated by default as identity primary key,
    property_id bigint not null,
    method_code varchar(80) not null,
    ledger_code varchar(80) not null,
    online_enabled boolean not null,
    constraint fk_payment_method_property foreign key (property_id) references property(id)
);

create table payment_gateway_config (
    id bigint generated by default as identity primary key,
    property_id bigint not null unique,
    provider_name varchar(120) not null,
    merchant_id varchar(120) not null,
    api_key_encrypted varchar(500) not null,
    secret_encrypted varchar(500) not null,
    mode varchar(30) not null,
    auto_capture boolean not null,
    three_ds_enabled boolean not null,
    constraint fk_gateway_property foreign key (property_id) references property(id)
);

create table tax_rule (
    id bigint generated by default as identity primary key,
    property_id bigint not null,
    tax_name varchar(120) not null,
    tax_type varchar(40) not null,
    calculation_type varchar(40) not null,
    tax_value double precision not null,
    applies_per_night boolean not null,
    priority integer not null,
    constraint fk_tax_rule_property foreign key (property_id) references property(id)
);

create index idx_room_type_property on room_type(property_id);
create index idx_floor_property on floor_configuration(property_id);
create index idx_inventory_property on inventory_room(property_id);
create index idx_coa_property on chart_of_account(property_id);
create index idx_revenue_mapping_property on revenue_mapping(property_id);
create index idx_payment_method_property on payment_method(property_id);
create index idx_tax_rule_property on tax_rule(property_id);


